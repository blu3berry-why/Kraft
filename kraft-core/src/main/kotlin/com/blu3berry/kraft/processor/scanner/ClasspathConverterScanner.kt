package com.blu3berry.kraft.processor.scanner

import com.google.devtools.ksp.KspExperimental
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.symbol.KSAnnotation
import com.google.devtools.ksp.symbol.KSFunctionDeclaration
import com.google.devtools.ksp.symbol.Origin
import com.blu3berry.kraft.model.scan.ConverterEntry
import com.blu3berry.kraft.model.scan.ConverterTypeKey
import com.blu3berry.kraft.model.scan.GlobalConverterRegistry
import com.blu3berry.kraft.processor.util.DelegateNaming
import com.blu3berry.kraft.processor.util.KraftKspConstants
import com.blu3berry.kraft.processor.util.buildConverterTypeKey

/**
 * Discovers `@KraftConverterDelegate`-annotated extension functions generated by
 * upstream Kraft modules into package [KraftKspConstants.GENERATED_REGISTRY_PACKAGE].
 *
 * Two mechanisms, because KSP exposes different capabilities per backend:
 *
 * 1. [scan] — package enumeration via `Resolver.getDeclarationsFromPackage(...)`.
 *    Works on JVM compilations (class-file classpath), where it indexes every
 *    delegate upfront regardless of its name. Returns nothing for klib dependencies
 *    (KMP metadata compilations), which is why mechanism 2 exists.
 * 2. [lookupByName] — on-demand resolution via `Resolver.getFunctionDeclarationsByName`,
 *    which *does* cross klib boundaries. The delegate's name is a pure function of the
 *    converter's type pair (see [DelegateNaming]), so the consumer can construct the
 *    expected FQN for any unresolved pair and ask for it directly. Wired as the
 *    lazy fallback of the merged [GlobalConverterRegistry]; eager entries win, so
 *    same-module `@KraftConverter` declarations shadow classpath delegates.
 *
 * Ambiguity *between* classpath modules — two different modules registering the same
 * `(source, target)` pair — produces a KSP error pointing at both delegates: on the
 * JVM path inside [scan], on the klib path inside [lookupByName] (same-FQN functions
 * from two klibs both come back from the by-name lookup).
 *
 * Delegates published by Kraft ≤ 0.10.x use index-based names and therefore stay
 * invisible to [lookupByName]; they are still found by [scan] on JVM. KMP cross-module
 * discovery never worked on those versions, so nothing regresses.
 */
class ClasspathConverterScanner(
    private val resolver: Resolver,
    private val logger: KSPLogger
) {
    private val byNameCache = mutableMapOf<ConverterTypeKey, ConverterEntry?>()

    /**
     * @param sameModuleKeys keys already registered by the same-module
     *                       [GlobalConverterScanner]. Pairs covered locally are
     *                       silently dropped from the classpath registry — the
     *                       local override wins and any upstream-vs-upstream
     *                       ambiguity for those pairs is not reported, since the
     *                       user has already disambiguated via a same-module
     *                       `@KraftConverter`.
     */
    @OptIn(KspExperimental::class)
    fun scan(sameModuleKeys: Set<ConverterTypeKey> = emptySet()): GlobalConverterRegistry {
        val packageName = KraftKspConstants.GENERATED_REGISTRY_PACKAGE
        val delegates = resolver.getDeclarationsFromPackage(packageName)
            .filterIsInstance<KSFunctionDeclaration>()
            .filter(::isLibraryDelegate)
            .toList()

        if (delegates.isEmpty()) return GlobalConverterRegistry.EMPTY

        val entries = mutableMapOf<ConverterTypeKey, ConverterEntry>()
        for (fn in delegates) {
            registerDelegate(fn, entries, sameModuleKeys)
        }
        return GlobalConverterRegistry(entries.toMap())
    }

    /**
     * Resolves the classpath delegate for [key] by its deterministic name — the
     * klib-compatible path. Results (including misses) are memoized per scanner
     * instance, i.e. per processing round. Misses are cached with an explicit
     * containsKey check — getOrPut can't distinguish a stored null from an absent
     * key, so it would re-run the resolver query on every miss.
     */
    fun lookupByName(key: ConverterTypeKey): ConverterEntry? {
        if (byNameCache.containsKey(key)) return byNameCache[key]
        return resolveByName(key).also { byNameCache[key] = it }
    }

    private fun resolveByName(key: ConverterTypeKey): ConverterEntry? {
        val fqName = "${KraftKspConstants.GENERATED_REGISTRY_PACKAGE}.${DelegateNaming.delegateNameFor(key)}"
        val matches = resolver
            .getFunctionDeclarationsByName(resolver.getKSNameFromString(fqName), includeTopLevel = true)
            .filter(::isLibraryDelegate)
            .filter { fn -> resolveDelegateKey(fn) == key }
            .toList()

        if (matches.size > 1) {
            reportClasspathAmbiguity(key, matches[0], matches[1])
        }
        return matches.firstOrNull()?.let(ConverterEntry::Real)
    }

    private fun isLibraryDelegate(fn: KSFunctionDeclaration): Boolean =
        (fn.origin == Origin.KOTLIN_LIB || fn.origin == Origin.JAVA_LIB) &&
            fn.annotations.any(::isDelegateAnnotation)

    private fun isDelegateAnnotation(annotation: KSAnnotation): Boolean =
        annotation.annotationType.resolve().declaration.qualifiedName?.asString() ==
            KraftKspConstants.FQ_KRAFT_CONVERTER_DELEGATE

    private fun registerDelegate(
        fn: KSFunctionDeclaration,
        entries: MutableMap<ConverterTypeKey, ConverterEntry>,
        sameModuleKeys: Set<ConverterTypeKey>
    ) {
        val key = resolveDelegateKey(fn) ?: return

        // The local @KraftConverter shadows any upstream entry for this pair, so
        // we don't need to record (and certainly don't need to error on) classpath
        // duplicates that the user has already disambiguated locally.
        if (key in sameModuleKeys) return

        val existing = entries[key]
        if (existing != null) {
            // Classpath delegates are always discovered as KSFunctionDeclaration,
            // so existing must be Real here; report against the underlying function.
            if (existing is ConverterEntry.Real) reportClasspathAmbiguity(key, existing.function, fn)
        } else {
            entries[key] = ConverterEntry.Real(fn)
        }
    }

    private fun resolveDelegateKey(fn: KSFunctionDeclaration): ConverterTypeKey? {
        val receiver = fn.extensionReceiver?.resolve() ?: return null
        val returnType = fn.returnType?.resolve() ?: return null
        // Generic delegates aren't generated by GlobalConverterScanner (which rejects them),
        // but if an upstream module produced one, drop it silently — same v1 limitation applies.
        if (receiver.arguments.isNotEmpty() || returnType.arguments.isNotEmpty()) return null
        return buildConverterTypeKey(receiver, returnType)
    }

    private fun reportClasspathAmbiguity(
        key: ConverterTypeKey,
        existing: KSFunctionDeclaration,
        duplicate: KSFunctionDeclaration
    ) {
        val source = "${key.sourceFqName}${if (key.sourceNullable) "?" else ""}"
        val target = "${key.targetFqName}${if (key.targetNullable) "?" else ""}"
        logger.error(
            "Ambiguous @KraftConverter on the classpath for ($source → $target): " +
                "registered by ${describeDelegate(existing)} and ${describeDelegate(duplicate)}. " +
                "Disambiguate by adding a same-module @KraftConverter or a per-property @MapUsing.",
            duplicate
        )
    }

    /**
     * Names the delegate's producing module when the delegate carries one. Delegates
     * for the same pair share the same function name by design, so the module id is
     * the only thing that distinguishes the two sides of an ambiguity report.
     */
    private fun describeDelegate(fn: KSFunctionDeclaration): String {
        val moduleId = fn.annotations.firstOrNull(::isDelegateAnnotation)
            ?.arguments
            ?.firstOrNull { it.name?.asString() == "moduleId" }
            ?.value as? String
        val fqName = fn.qualifiedName?.asString() ?: fn.simpleName.asString()
        return if (moduleId.isNullOrBlank()) "'$fqName'" else "Kraft module '$moduleId' ('$fqName')"
    }
}
